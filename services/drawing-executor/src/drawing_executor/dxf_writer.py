def _title_block(msp, cd: CompiledDrawing, generator: str) -> None:
    tb = cd.title_block
    F = {f.label: f.value for f in cd.title_fields}
    sx = tb.w / _TB_W
    sy = tb.h / _TB_H

    def P(x, y):
        return (tb.x0 + x * sx, tb.y0 + y * sy)

    def label(text, x, y_top, h=1.8):
        _text(msp, text, P(x + 1.0, y_top - 1.0 - h), h, "TITLE")

    def value(text, x0, x1, y0, y1, h, align="MC", h_min=1.2):
        text, h = _fit(text, (x1 - x0) * sx - 2.0, h, h_min)
        if align == "MC":
            _text(msp, text, P((x0 + x1) / 2, (y0 + y1) / 2), h, "TITLE", "MC")
        else:
            _text(msp, text, P(x0 + 1.0, (y0 + y1) / 2), h, "TITLE", "ML")

    _rect(msp, tb, "FRAME")
    for kind, a, b, c in _TB_LINES:
        if kind == "h":
            _line(msp, P(b, a), P(c, a), "TITLE")
        else:
            _line(msp, P(a, b), P(a, c), "TITLE")

    # UNLESS OTHERWISE SPECIFIED block (general requirements - values only when supplied)
    block = [
        "UNLESS OTHERWISE SPECIFIED:",
        "DIMENSIONS ARE IN MILLIMETERS",
        f"SURFACE FINISH: {F.get('SURFACE_FINISH', 'UNSPECIFIED')}",
        "TOLERANCES:",
        f"   LINEAR: {F.get('LINEAR_TOL', 'UNSPECIFIED')}",
        f"   ANGULAR: {F.get('ANGULAR_TOL', 'UNSPECIFIED')}",
    ]
    y = 55.0 - 0.6
    for line in block:
        t, h = _fit(line, 33.9 * sx - 2.0, 1.5, 0.9)
        y -= 2.6
        _text(msp, t, P(1.0, y), h, "TITLE")
    label("FINISH:", 33.9, 55.0)
    value(F.get("FINISH", ""), 33.9, 80.5, 38.2, 49.0, 2.5)
    edges = F.get("EDGES", "")
    if edges:
        lines = edges.split("\n")
        for k, line in enumerate(lines):
            t, h = _fit(line, 18.3 * sx - 2.0, 1.8)
            _text(msp, t, P(89.65, 52.0 - k * 3.0), h, "TITLE", "MC")
    value("DO NOT SCALE DRAWING", 98.8, 150.5, 48.9, 55.0, 2.5)
    label("REVISION", 150.5, 55.0, 1.5)
    value(F.get("REVISION", ""), 162.0, 180.0, 48.9, 55.0, 3.0)
    value(F.get("ORGANIZATION", ""), 98.8, 180.0, 38.2, 48.9, 3.5)

    # sign-off table
    for name, (a, b) in zip(("NAME", "SIGNATURE", "DATE"), zip(_SIGN_COLS[1:], _SIGN_COLS[2:])):
        value(name, a, b, 33.9, 38.2, 1.8)
    for role, y0, y1 in _SIGN_ROWS[1:]:
        value(role, 0.0, 10.0, y0, y1, 1.6, "ML")
        key = {"DRAWN": "DRAWN", "CHK'D": "CHECKED", "APPV'D": "APPROVED", "MFG": "MFG", "Q.A": "QA"}[role]
        value(F.get(f"{key}_NAME", ""), 10.0, 27.3, y0, y1, 1.8, "ML")
        value(F.get(f"{key}_DATE", ""), 44.6, 54.5, y0, y1, 1.6, "ML", 0.9)

    # projection symbol + drawing standard
    third = F.get("PROJECTION", "FIRST_ANGLE").upper().startswith("THIRD")
    _projection_symbol(msp, *P(76.65, 31.0), third)
    value(("THIRD" if third else "FIRST") + " ANGLE PROJECTION", 54.5, 98.8, 22.5, 25.5, 1.8)
    extra = [f"{F.get('TYPE', '')}  ·  STANDARD: {F.get('STANDARD', '')}"]
    if F.get("PART_NO") and F.get("PART_NO") != F.get("DWG_NO"):
        extra.append(f"PART NO.: {F['PART_NO']}")
    if F.get("QTY"):
        extra.append(f"QTY: {F['QTY']}")
    for k, line in enumerate(extra[:2]):
        value(line, 54.5, 98.8, 19.6 - k * 2.7, 21.6 - k * 2.7, 1.6)

    label("MATERIAL:", 54.5, 16.9)
    value(F.get("MATERIAL", ""), 54.5, 98.8, 4.3, 13.0, 3.5)
    t, h = _fit(f"WEIGHT: {F.get('WEIGHT', '')}", 44.3 * sx - 2.0, 1.8)
    _text(msp, t, P(55.5, 2.15), h, "TITLE", "ML")
    label("TITLE:", 98.8, 38.2)
    value(F.get("TITLE", ""), 98.8, 180.0, 17.3, 34.5, 5.0, h_min=2.5)
    label("DWG NO.", 98.8, 17.3)
    value(F.get("DWG_NO", ""), 98.8, 166.8, 4.3, 13.5, 3.5)
    value(F.get("SHEET_SIZE", ""), 166.8, 180.0, 4.3, 17.3, 5.0)
    t, h = _fit(f"SCALE: {F.get('SCALE', '')}", 44.2 * sx - 2.0, 1.8)
    _text(msp, t, P(99.8, 2.15), h, "TITLE", "ML")
    t, h = _fit(f"SHEET {F.get('SHEET', '1 OF 1')}", 37.0 * sx - 2.0, 1.8)
    _text(msp, t, P(144.0, 2.15), h, "TITLE", "ML")

    # provenance (kept inside the title block - never presented as SolidWorks output)
    prov = _wrap(PROVENANCE, 52) + [f"EXECUTOR: {generator}", f"DATE: {F.get('DATE', '')}"]
    for k, line in enumerate(prov[:4]):
        t, h = _fit(line, 54.5 * sx - 2.0, 1.2, 0.7)
        _text(msp, t, P(1.0, 10.4 - k * 2.6), h, "TITLE")


def _wrap(text: str, n: int) -> list[str]:
    out, cur = [], ""
    for w in text.split():
        if cur and len(cur) + 1 + len(w) > n:
            out.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    return out + ([cur] if cur else [])


def _sheet_notes(msp, cd: CompiledDrawing) -> None:
    if not cd.sheet_notes or cd.notes_rect is None:
        return
    r = cd.notes_rect
    y = r.y1 - 1.0 - 3.0
    _text(msp, "Note:", (r.x0 + 1.0, y), 3.0, "NOTES")
    for line in cd.sheet_notes:
        y -= 5.0
        t, h = _fit(line, r.w - 8.0, 3.0, 2.0)
        _text(msp, t, (r.x0 + 6.0, y), h, "NOTES")


def _revision_table(msp, cd: CompiledDrawing) -> None:
    if not cd.revision_rows or cd.revision_rect is None:
        return
    r = cd.revision_rect
    rh = r.h / (len(cd.revision_rows) + 2)
    cols = [r.x0, r.x0 + 0.1 * r.w, r.x0 + 0.6 * r.w, r.x0 + 0.8 * r.w, r.x1]
    _rect(msp, r, "FRAME")
    for k in range(1, len(cd.revision_rows) + 2):
        _line(msp, (r.x0, r.y1 - k * rh), (r.x1, r.y1 - k * rh), "TITLE")
    for x in cols[1:-1]:
        _line(msp, (x, r.y0), (x, r.y1 - rh), "TITLE")
    _text(msp, "REVISIONS", ((r.x0 + r.x1) / 2, r.y1 - rh / 2), 2.5, "TITLE", "MC")
    rows = [["REV.", "DESCRIPTION", "DATE", "APPROVED"], *cd.revision_rows]
    for i, row in enumerate(rows):
        yc = r.y1 - (i + 1.5) * rh
        for j, cell in enumerate(row):
            t, h = _fit(cell, cols[j + 1] - cols[j] - 2.0, 2.5 if i else 2.0)
            _text(msp, t, ((cols[j] + cols[j + 1]) / 2, yc), h, "TITLE", "MC")


