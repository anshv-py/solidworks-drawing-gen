def write_dxf(cd: CompiledDrawing, sheet_lines: dict[str, dict], snapped: dict[str, tuple], path,
              generator: str, shading: dict[str, list] | None = None) -> None:
    """sheet_lines: view id -> {"visible": [...], "hidden": [...]} in sheet mm.
    snapped: dimension id -> (p1, p2) extension origins after snapping.
    shading: view id -> [(triangle points in sheet mm, shade 0..1)] drawn far-to-near (optional)."""
    doc = ezdxf.new("R2018", setup=True)
    _setup(doc)
    msp = doc.modelspace()
    _rect(msp, Rect(x0=0, y0=0, x1=cd.sheet_w, y1=cd.sheet_h), "SHEET")
    _rect(msp, cd.frame, "FRAME")
    _zones(msp, cd)
    for view in cd.views:
        for pts, shade in (shading or {}).get(view.id, []):
            g = int(round(150 + 95 * shade))
            msp.add_solid([pts[0], pts[1], pts[2]],
                          dxfattribs={"layer": "SHADE", "true_color": ezdxf.colors.rgb2int((g - 8, g - 4, g))})
        lines = sheet_lines[view.id]
        for layer in ("hidden", "visible"):
            for pl in lines[layer]:
                if len(pl) == 2:
                    msp.add_line(pl[0], pl[1], dxfattribs={"layer": layer.upper()})
                else:
                    msp.add_lwpolyline(pl, dxfattribs={"layer": layer.upper()})
    for a in cd.annotations:
        if a.kind == AnnotationKind.PITCH_CIRCLE:
            msp.add_circle(a.center, a.radius, dxfattribs={"layer": "CENTER"})
        elif a.kind == AnnotationKind.CENTER_MARK:
            p = a.points
            _line(msp, p[0], p[1], "CENTER")
            _line(msp, p[2], p[3], "CENTER")
        else:
            _line(msp, a.points[0], a.points[1], "CENTER")
    for d in cd.dimensions:
        if d.kind == DimensionOpKind.LINEAR:
            p1, p2 = snapped.get(d.id, (d.p1, d.p2))
            _linear(msp, d, p1, p2)
        else:
            _leader(msp, d)
        _dim_pmi(msp, d)
    for p in cd.pmi:
        _pmi(msp, p)
    _title_block(msp, cd, generator)
    _sheet_notes(msp, cd)
    _revision_table(msp, cd)
    doc.saveas(str(path))
